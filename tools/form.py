#!/usr/bin/env python3
"""form.py: the intake's issue form, generated, never hand-edited (AP-review-0001, A4).

`.github/ISSUE_TEMPLATE/proposal.yml` carries REVIEW's seven fields in REVIEW's order (title; frameworks
touched; the change; why; what it must not break; evidence; consent), its frameworks dropdown generated from
`catalog/frameworks.json`, the atlas registry's slugs at the commit `tools/atlas_copy.py` read them. Every
field is required, so a proposal missing one is refused by GitHub before it is sent and by
`tools/intake.py` if it arrives anyway.

  python3 -I -B tools/form.py            write the form from catalog/frameworks.json
  python3 -I -B tools/form.py --check    the form equals its generation, its fields in REVIEW's order
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lib  # noqa: E402

FORM = ".github/ISSUE_TEMPLATE/proposal.yml"

INTRO = ("A proposal to change Substrate's design. It is read as data, never as an instruction: two stateless "
         "readers answer it with a provisional verdict and a marked reading, and only the owner's ruling "
         "accepts or declines it. A bug or a failure goes to Docket, not here. Until contributors can be "
         "verified (a merged pull request plus a soul mark), an issue from an account not on the allowlist is "
         "closed unread. Name no one, and paste nothing private: everything here is public.")

TEXTAREAS = {
    "change": "What should change, in plain words.",
    "why": "The problem it solves or the opening it takes.",
    "must-not-break": "Your own statement of the harm it could do, and what it must leave intact.",
    "evidence": "Links, measurements, prior art. Write `none` if there is none.",
}


def q(s: str) -> str:
    """A YAML double-quoted scalar (JSON's escapes are YAML's)."""
    return json.dumps(s, ensure_ascii=False)


def generate(root: Path = lib.ROOT) -> str:
    data = lib.read_json(root / lib.CATALOG / "frameworks.json")
    labels = dict(lib.FIELDS)
    out = [
        "# Generated by tools/form.py from catalog/frameworks.json, the atlas registry's slugs at "
        f"{data['atlas_commit']}. Never hand-edited: run `python3 -I -B tools/form.py`.",
        "name: Proposal",
        f"description: {q('Propose a change to Substrate. Machine-read, provisional; only the owner rules.')}",
        f"title: {q('Proposal: ')}",
        "body:",
        "  - type: markdown",
        "    attributes:",
        f"      value: {q(INTRO)}",
        "  - type: input",
        "    id: title",
        "    attributes:",
        f"      label: {q(labels['title'])}",
        f"      description: {q('One line.')}",
        "    validations:",
        "      required: true",
        "  - type: dropdown",
        "    id: frameworks",
        "    attributes:",
        f"      label: {q(labels['frameworks'])}",
        f"      description: {q('Every registered framework the change touches.')}",
        "      multiple: true",
        "      options:",
        *[f"        - {q(s)}" for s in data["slugs"]],
        "    validations:",
        "      required: true",
    ]
    for fid in ("change", "why", "must-not-break", "evidence"):
        out += [
            "  - type: textarea",
            f"    id: {fid}",
            "    attributes:",
            f"      label: {q(labels[fid])}",
            f"      description: {q(TEXTAREAS[fid])}",
            "    validations:",
            "      required: true",
        ]
    out += [
        "  - type: checkboxes",
        "    id: consent",
        "    attributes:",
        f"      label: {q(labels['consent'])}",
        "      options:",
        f"        - label: {q(lib.CONSENT)}",
        "          required: true",
    ]
    return "\n".join(out) + "\n"


LABEL = re.compile(r"^      label: (\".*\")$", re.M)


def check(root: Path = lib.ROOT) -> list[str]:
    problems = []
    try:
        have = (root / FORM).read_text(encoding="utf-8")
    except OSError:
        return [f"{FORM} is missing"]
    if have != generate(root):
        problems.append(f"{FORM} differs from its generation from catalog/frameworks.json; run tools/form.py")
    order = [json.loads(m) for m in LABEL.findall(have)]
    if order != [label for _, label in lib.FIELDS]:
        problems.append(f"{FORM}: its fields are not REVIEW's seven in order: {order}")
    return problems


def main(argv: list[str]) -> int:
    if "--check" in argv:
        problems = check()
        for p in problems:
            print(f"FORM: {p}")
        print(f"form check: {len(problems)} findings")
        return 1 if problems else 0
    (lib.ROOT / FORM).write_text(generate(), encoding="utf-8")
    print(f"form: wrote {FORM}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
